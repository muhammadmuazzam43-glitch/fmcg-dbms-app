import React, { useState } from 'react';
import { Product, Supplier, PurchaseOrder, UserRole, StockAlert } from '../types/inventory';
import { AlertTriangle, Clock, RefreshCw, CheckCircle2, ArrowRight, Truck, FileText, Plus, ShieldAlert } from 'lucide-react';
import { playSuccessChime, playLowStockAlertChime } from '../utils/audio';

interface ReplenishmentWorkflowProps {
  products: Product[];
  suppliers: Supplier[];
  purchaseOrders: PurchaseOrder[];
  currentRole: UserRole;
  onCreatePurchaseOrder: (po: PurchaseOrder) => void;
  onUpdatePurchaseOrderStatus: (poId: string, status: PurchaseOrder['status']) => void;
}

export const ReplenishmentWorkflow: React.FC<ReplenishmentWorkflowProps> = ({
  products,
  suppliers,
  purchaseOrders,
  currentRole,
  onCreatePurchaseOrder,
  onUpdatePurchaseOrderStatus,
}) => {
  const [activeTab, setActiveTab] = useState<'alerts' | 'purchase_orders' | 'supplier_performance'>('alerts');

  // Compute Active Low Stock & Stockout Alerts based on the exact rule from Slide 6
  const alerts: StockAlert[] = products
    .filter((p) => p.quantityOnHand <= p.reorderPoint)
    .map((p) => {
      const supplier = suppliers.find((s) => s.id === p.primarySupplierId);
      // Calculate pending PO quantity
      const pendingQty = purchaseOrders
        .filter((po) => po.status === 'Sent' || po.status === 'In Transit')
        .flatMap((po) => po.items)
        .filter((item) => item.productId === p.id)
        .reduce((sum, item) => sum + (item.quantityRequested - item.quantityReceived), 0);

      // Slide 6 Recommended Quantity Formula:
      // Q_rec = max(0, (safety_stock + (daily_velocity * lead_time)) - (quantity_on_hand + incoming_stock))
      const targetBuffer = p.safetyStock + p.dailyVelocity * p.leadTimeDays;
      const currentCoverage = p.quantityOnHand + pendingQty;
      const recommendedQty = Math.max(50, Math.ceil(targetBuffer - currentCoverage));

      const isStockout = p.quantityOnHand === 0;

      return {
        id: `ALT-${p.sku}`,
        productId: p.id,
        sku: p.sku,
        productName: p.name,
        type: isStockout ? 'STOCKOUT' : 'LOW_STOCK',
        severity: isStockout ? 'CRITICAL' : 'WARNING',
        currentValue: p.quantityOnHand,
        thresholdValue: p.reorderPoint,
        recommendedOrderQty: recommendedQty,
        supplierId: supplier?.id || 'SUP-001',
        supplierName: supplier?.name || 'Apex Beverages',
        message: isStockout
          ? `CRITICAL STOCKOUT: Current balance is 0. Safety buffer depleted.`
          : `LOW STOCK THRESHOLD: Balance (${p.quantityOnHand}) is at or below reorder point (${p.reorderPoint}).`,
        timestamp: 'Real-time DBMS Trigger',
        acknowledged: pendingQty > 0,
      };
    });

  const handleGenerateAutomatedPO = (alert: StockAlert) => {
    const prod = products.find((p) => p.id === alert.productId);
    if (!prod) return;

    const supplier = suppliers.find((s) => s.id === alert.supplierId) || suppliers[0];
    const newPoId = `PO-2026-${Math.floor(1000 + Math.random() * 9000)}`;

    const deliveryDate = new Date();
    deliveryDate.setDate(deliveryDate.getDate() + (supplier.leadTimeDays || 4));

    const newPO: PurchaseOrder = {
      id: newPoId,
      supplierId: supplier.id,
      supplierName: supplier.name,
      status: 'Approved',
      createdAt: new Date().toISOString().split('T')[0],
      expectedDeliveryDate: deliveryDate.toISOString().split('T')[0],
      items: [
        {
          productId: prod.id,
          sku: prod.sku,
          productName: prod.name,
          quantityRequested: alert.recommendedOrderQty,
          quantityReceived: 0,
          unitCost: prod.unitCost,
          totalCost: alert.recommendedOrderQty * prod.unitCost,
        },
      ],
      totalAmount: Number((alert.recommendedOrderQty * prod.unitCost).toFixed(2)),
      isDelayed: false,
      notes: `Automated replenishment PO generated by Reorder Rule Engine for ${prod.sku}.`,
    };

    onCreatePurchaseOrder(newPO);
    playSuccessChime();
  };

  return (
    <div className="space-y-6">
      {/* View Header */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4 pb-2 border-b border-slate-800">
        <div>
          <h1 className="text-xl font-bold tracking-tight text-white flex items-center gap-2">
            <RefreshCw className="w-5 h-5 text-cyan-400" />
            <span>Procurement &amp; Replenishment Engine</span>
          </h1>
          <p className="text-xs text-slate-400 mt-0.5">
            Automated Reorder Point evaluation, mathematical safety stock sizing, and supplier PO lifecycle
          </p>
        </div>

        {/* Tab navigation */}
        <div className="flex items-center gap-1 p-1 bg-slate-900 border border-slate-800 rounded-lg">
          <button
            onClick={() => setActiveTab('alerts')}
            className={`px-3 py-1.5 text-xs font-medium rounded-md transition-colors cursor-pointer ${
              activeTab === 'alerts'
                ? 'bg-slate-800 text-cyan-400 shadow-sm'
                : 'text-slate-400 hover:text-white'
            }`}
          >
            Low Stock Alerts ({alerts.length})
          </button>
          <button
            onClick={() => setActiveTab('purchase_orders')}
            className={`px-3 py-1.5 text-xs font-medium rounded-md transition-colors cursor-pointer ${
              activeTab === 'purchase_orders'
                ? 'bg-slate-800 text-cyan-400 shadow-sm'
                : 'text-slate-400 hover:text-white'
            }`}
          >
            Purchase Orders ({purchaseOrders.length})
          </button>
          <button
            onClick={() => setActiveTab('supplier_performance')}
            className={`px-3 py-1.5 text-xs font-medium rounded-md transition-colors cursor-pointer ${
              activeTab === 'supplier_performance'
                ? 'bg-slate-800 text-cyan-400 shadow-sm'
                : 'text-slate-400 hover:text-white'
            }`}
          >
            Supplier SLA Matrix
          </button>
        </div>
      </div>

      {/* Intelligence Engine Specification Banner (Slide 6) */}
      <div className="p-4 bg-slate-900 border border-slate-800 rounded-lg">
        <h2 className="text-xs font-semibold uppercase tracking-wider text-cyan-400 mb-2">
          Replenishment Formula Specification
        </h2>
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4 text-xs">
          <div className="p-3 bg-slate-950 border border-slate-800/80 rounded">
            <div className="font-semibold text-slate-200">Reorder Trigger Rule</div>
            <code className="text-cyan-300 font-mono block mt-1">
              IF quantity_on_hand &le; reorder_point &rarr; GENERATE_ALERT
            </code>
            <p className="text-slate-400 mt-1.5 text-[11px]">
              Evaluated on every sale, adjustment, or physical audit transaction.
            </p>
          </div>
          <div className="p-3 bg-slate-950 border border-slate-800/80 rounded">
            <div className="font-semibold text-slate-200">Recommended Order Sizing</div>
            <code className="text-cyan-300 font-mono block mt-1">
              Q_rec = (Safety_Stock + (Daily_Velocity &times; Lead_Time)) &minus; (On_Hand + Pending_POs)
            </code>
            <p className="text-slate-400 mt-1.5 text-[11px]">
              Ensures optimal inventory level without capital tie-up or stockouts.
            </p>
          </div>
        </div>
      </div>

      {/* Tab 1: Active Low Stock Alerts */}
      {activeTab === 'alerts' && (
        <div className="space-y-4">
          {alerts.length === 0 ? (
            <div className="p-8 bg-slate-900 border border-slate-800 rounded-lg text-center space-y-2">
              <CheckCircle2 className="w-8 h-8 text-emerald-400 mx-auto" />
              <div className="text-sm font-semibold text-white">All Stock Levels Nominal</div>
              <p className="text-xs text-slate-400">
                All SKU inventory quantities exceed their respective safety stock and reorder thresholds.
              </p>
            </div>
          ) : (
            <div className="grid grid-cols-1 gap-3">
              {alerts.map((alert) => {
                const prod = products.find((p) => p.id === alert.productId);

                return (
                  <div
                    key={alert.id}
                    className={`p-4 bg-slate-900 border rounded-lg flex flex-col md:flex-row md:items-center justify-between gap-4 transition-all ${
                      alert.severity === 'CRITICAL'
                        ? 'border-rose-500/40'
                        : 'border-amber-500/40'
                    }`}
                  >
                    <div className="space-y-1.5">
                      <div className="flex items-center gap-2">
                        <span
                          className={`text-[10px] font-mono font-bold px-2 py-0.5 rounded border uppercase ${
                            alert.severity === 'CRITICAL'
                              ? 'bg-rose-950 text-rose-300 border-rose-800'
                              : 'bg-amber-950 text-amber-300 border-amber-800'
                          }`}
                        >
                          {alert.type}
                        </span>
                        <span className="font-mono text-xs font-semibold text-white">
                          {alert.sku}
                        </span>
                        <span className="text-slate-500">·</span>
                        <span className="text-xs text-slate-300 font-medium">
                          {alert.productName}
                        </span>
                      </div>

                      <p className="text-xs text-slate-400">{alert.message}</p>

                      <div className="flex flex-wrap items-center gap-3 text-xs text-slate-400 pt-1">
                        <span>
                          Current Balance:{' '}
                          <strong className={alert.currentValue === 0 ? 'text-rose-400 font-mono' : 'text-amber-400 font-mono'}>
                            {alert.currentValue} units
                          </strong>
                        </span>
                        <span>·</span>
                        <span>
                          Reorder Threshold: <strong className="text-slate-200 font-mono">{alert.thresholdValue}</strong>
                        </span>
                        <span>·</span>
                        <span>
                          Supplier: <strong className="text-slate-200">{alert.supplierName}</strong>
                        </span>
                        <span>·</span>
                        <span>
                          Optimal PO Sizing:{' '}
                          <strong className="text-cyan-400 font-mono font-bold">
                            +{alert.recommendedOrderQty} units
                          </strong>
                        </span>
                      </div>
                    </div>

                    <div className="flex items-center gap-2 shrink-0">
                      <button
                        onClick={() => handleGenerateAutomatedPO(alert)}
                        className="px-3.5 py-2 text-xs font-semibold text-slate-950 bg-cyan-400 hover:bg-cyan-300 rounded-md transition-colors cursor-pointer flex items-center gap-1.5 whitespace-nowrap"
                      >
                        <Plus className="w-3.5 h-3.5" />
                        <span>Create PO (+{alert.recommendedOrderQty})</span>
                      </button>
                    </div>
                  </div>
                );
              })}
            </div>
          )}
        </div>
      )}

      {/* Tab 2: Purchase Orders Table */}
      {activeTab === 'purchase_orders' && (
        <div className="border border-slate-800 rounded-lg overflow-hidden bg-slate-900">
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs border-collapse">
              <thead>
                <tr className="bg-slate-950/80 border-b border-slate-800 text-slate-400 uppercase tracking-wider font-semibold text-[11px]">
                  <th className="py-2.5 px-3">PO Number</th>
                  <th className="py-2.5 px-3">Supplier</th>
                  <th className="py-2.5 px-3">Created Date</th>
                  <th className="py-2.5 px-3">Expected Delivery</th>
                  <th className="py-2.5 px-3 text-right">Items &amp; Qty</th>
                  <th className="py-2.5 px-3 text-right">Total Amount</th>
                  <th className="py-2.5 px-3">Status</th>
                  <th className="py-2.5 px-3 text-right">Action</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-800/80">
                {purchaseOrders.map((po) => {
                  const totalUnits = po.items.reduce((s, i) => s + i.quantityRequested, 0);

                  return (
                    <tr key={po.id} className="hover:bg-slate-800/40 transition-colors">
                      <td className="py-2.5 px-3 font-mono font-semibold text-cyan-400">
                        {po.id}
                      </td>
                      <td className="py-2.5 px-3 font-medium text-white">
                        {po.supplierName}
                      </td>
                      <td className="py-2.5 px-3 font-mono text-slate-400">
                        {po.createdAt}
                      </td>
                      <td className="py-2.5 px-3 font-mono text-slate-300">
                        <span className={po.isDelayed ? 'text-rose-400 font-semibold' : ''}>
                          {po.expectedDeliveryDate}
                        </span>
                        {po.isDelayed && (
                          <span className="ml-1 text-[10px] text-rose-400">(Delayed)</span>
                        )}
                      </td>
                      <td className="py-2.5 px-3 text-right font-mono tabular-nums text-slate-300">
                        {po.items.length} SKUs ({totalUnits} units)
                      </td>
                      <td className="py-2.5 px-3 text-right font-mono tabular-nums font-bold text-white">
                        ${po.totalAmount.toFixed(2)}
                      </td>
                      <td className="py-2.5 px-3 whitespace-nowrap">
                        <span
                          className={`text-[11px] font-semibold px-2 py-0.5 rounded ${
                            po.status === 'Delivered'
                              ? 'bg-emerald-950 text-emerald-400'
                              : po.status === 'Delayed'
                              ? 'bg-rose-950 text-rose-400'
                              : po.status === 'In Transit'
                              ? 'bg-cyan-950 text-cyan-400'
                              : 'bg-slate-800 text-slate-300'
                          }`}
                        >
                          {po.status}
                        </span>
                      </td>
                      <td className="py-2.5 px-3 text-right whitespace-nowrap">
                        {po.status !== 'Delivered' ? (
                          <button
                            onClick={() => onUpdatePurchaseOrderStatus(po.id, 'Delivered')}
                            className="px-2.5 py-1 text-[11px] font-medium text-emerald-300 bg-emerald-950/40 hover:bg-emerald-900/50 border border-emerald-800/40 rounded cursor-pointer"
                            title="Perform Goods Receipt and credit stock balance"
                          >
                            Receive Goods
                          </button>
                        ) : (
                          <span className="text-[11px] text-slate-500 font-mono">Completed</span>
                        )}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {/* Tab 3: Supplier Performance & Delays (Slide 5) */}
      {activeTab === 'supplier_performance' && (
        <div className="space-y-4">
          <div className="border border-slate-800 rounded-lg overflow-hidden bg-slate-900">
            <div className="overflow-x-auto">
              <table className="w-full text-left text-xs border-collapse">
                <thead>
                  <tr className="bg-slate-950/80 border-b border-slate-800 text-slate-400 uppercase tracking-wider font-semibold text-[11px]">
                    <th className="py-2.5 px-3">Supplier Name &amp; Code</th>
                    <th className="py-2.5 px-3">Category</th>
                    <th className="py-2.5 px-3 text-right">Lead Time</th>
                    <th className="py-2.5 px-3 text-right">On-Time Delivery (OTDR)</th>
                    <th className="py-2.5 px-3 text-right">Quality Score</th>
                    <th className="py-2.5 px-3">Payment Terms</th>
                    <th className="py-2.5 px-3">SLA Status</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-800/80">
                  {suppliers.map((s) => (
                    <tr key={s.id} className="hover:bg-slate-800/40 transition-colors">
                      <td className="py-2.5 px-3">
                        <div className="font-semibold text-white">{s.name}</div>
                        <div className="font-mono text-[11px] text-slate-400">{s.code} · {s.email}</div>
                      </td>
                      <td className="py-2.5 px-3 text-slate-300">{s.category}</td>
                      <td className="py-2.5 px-3 text-right font-mono tabular-nums text-slate-200">
                        {s.leadTimeDays} days
                      </td>
                      <td className="py-2.5 px-3 text-right font-mono tabular-nums font-semibold">
                        <span className={s.onTimeDeliveryRate < 90 ? 'text-rose-400' : 'text-emerald-400'}>
                          {s.onTimeDeliveryRate}%
                        </span>
                      </td>
                      <td className="py-2.5 px-3 text-right font-mono tabular-nums text-slate-200">
                        {s.qualityScore}/100
                      </td>
                      <td className="py-2.5 px-3 font-mono text-slate-400">{s.paymentTerms}</td>
                      <td className="py-2.5 px-3 whitespace-nowrap">
                        <span
                          className={`text-[11px] font-semibold px-2 py-0.5 rounded ${
                            s.status === 'Delayed'
                              ? 'bg-rose-950 text-rose-400'
                              : 'bg-emerald-950 text-emerald-400'
                          }`}
                        >
                          {s.status}
                        </span>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
